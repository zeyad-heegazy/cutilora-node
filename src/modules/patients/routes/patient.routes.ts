import { Router } from 'express';
import { authenticate } from '../../auth/middleware/authenticate.js';
import { resolveTenantContext } from '../../tenancy/middleware/tenant-context.js';
import { requireTenantPermission } from '../../tenancy/middleware/tenant-permissions.js';
import { patientController as c } from '../controllers/patient.controller.js';
import { patientTagController as tags } from '../controllers/patient-tag.controller.js';

export const patientRouter = Router();
const auth = [authenticate, resolveTenantContext] as const;
patientRouter.get('/patient-tags', ...auth, requireTenantPermission('patients.read'), tags.list);
patientRouter.post('/patient-tags', ...auth, requireTenantPermission('patients.manage'), tags.create);
patientRouter.get('/patients/search', ...auth, requireTenantPermission('patients.read'), c.list);
patientRouter.get('/patients', ...auth, requireTenantPermission('patients.read'), c.list);
patientRouter.post('/patients', ...auth, requireTenantPermission('patients.manage'), c.create);
patientRouter.get('/patients/:patientId', ...auth, requireTenantPermission('patients.read'), c.get);
patientRouter.patch('/patients/:patientId', ...auth, requireTenantPermission('patients.manage'), c.update);
patientRouter.get('/patients/:patientId/contacts', ...auth, requireTenantPermission('patients.read'), c.contacts);
patientRouter.put('/patients/:patientId/contacts', ...auth, requireTenantPermission('patients.manage'), c.replaceContacts);
patientRouter.put('/patients/:patientId/addresses', ...auth, requireTenantPermission('patients.manage'), c.replaceAddresses);
patientRouter.put('/patients/:patientId/emergency-contacts', ...auth, requireTenantPermission('patients.manage'), c.replaceEmergencyContacts);
patientRouter.get('/patients/:patientId/tags', ...auth, requireTenantPermission('patients.read'), c.tags);
patientRouter.put('/patients/:patientId/tags', ...auth, requireTenantPermission('patients.manage'), c.setTags);
patientRouter.get('/patients/:patientId/notes', ...auth, requireTenantPermission('patients.notes.read'), c.getNotes);
patientRouter.post('/patients/:patientId/notes', ...auth, requireTenantPermission('patients.notes.manage'), c.addNote);
patientRouter.get('/patients/:patientId/status-history', ...auth, requireTenantPermission('patients.read'), c.statusHistory);
patientRouter.patch('/patients/:patientId/status', ...auth, requireTenantPermission('patients.manage'), c.changeStatus);

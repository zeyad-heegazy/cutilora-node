import { Router } from 'express';
import { authenticatePlatform } from '../../auth/middleware/authenticate-platform.js';
import { requirePlatformPermission } from '../../auth/middleware/platform-permissions.js';
import { logController } from '../controllers/log.controller.js';
import { monitoringViewController } from '../controllers/monitoring-view.controller.js';
export const monitoringRouter = Router();
monitoringRouter.get('/view', monitoringViewController.show);
monitoringRouter.use(authenticatePlatform);
monitoringRouter.get('/logs', requirePlatformPermission('platform.monitoring.logs.read'), logController.list);
monitoringRouter.get('/logs/stats', requirePlatformPermission('platform.monitoring.logs.read'), logController.stats);
monitoringRouter.get('/logs/timeline', requirePlatformPermission('platform.monitoring.logs.read'), logController.timeline);
monitoringRouter.get('/logs/:id', requirePlatformPermission('platform.monitoring.logs.read'), logController.get);

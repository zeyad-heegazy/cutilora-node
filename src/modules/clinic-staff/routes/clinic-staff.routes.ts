import { Router } from 'express';
import { authenticate } from '../../auth/middleware/authenticate.js';
import { resolveTenantContext } from '../../tenancy/middleware/tenant-context.js';
import { requireTenantPermission } from '../../tenancy/middleware/tenant-permissions.js';
import { clinicStaffController as c } from '../controllers/clinic-staff.controller.js';

export const clinicStaffRouter = Router();
const staffAuth = [authenticate, resolveTenantContext] as const;
clinicStaffRouter.get('/employees', ...staffAuth, requireTenantPermission('staff.read'), c.listEmployees);
clinicStaffRouter.post('/employees', ...staffAuth, requireTenantPermission('staff.manage'), c.createEmployee);
clinicStaffRouter.get('/employees/:employeeId', ...staffAuth, requireTenantPermission('staff.read'), c.getEmployee);
clinicStaffRouter.patch('/employees/:employeeId', ...staffAuth, requireTenantPermission('staff.manage'), c.updateEmployee);
clinicStaffRouter.get('/providers', ...staffAuth, requireTenantPermission('providers.read'), c.listProviders);
clinicStaffRouter.post('/providers', ...staffAuth, requireTenantPermission('providers.manage'), c.createProvider);
clinicStaffRouter.get('/providers/:providerId', ...staffAuth, requireTenantPermission('providers.read'), c.getProvider);
clinicStaffRouter.patch('/providers/:providerId', ...staffAuth, requireTenantPermission('providers.manage'), c.updateProvider);
clinicStaffRouter.put('/providers/:providerId/branches', ...staffAuth, requireTenantPermission('providers.manage'), c.replaceProviderBranches);
clinicStaffRouter.put('/providers/:providerId/services', ...staffAuth, requireTenantPermission('providers.manage'), c.replaceProviderServices);
clinicStaffRouter.get('/providers/:providerId/working-hours', ...staffAuth, requireTenantPermission('providers.read'), c.getProviderWorkingHours);
clinicStaffRouter.put('/providers/:providerId/working-hours', ...staffAuth, requireTenantPermission('providers.manage'), c.setProviderWorkingHours);
clinicStaffRouter.get('/specialties', ...staffAuth, requireTenantPermission('providers.read'), c.listSpecialties);
clinicStaffRouter.post('/specialties', ...staffAuth, requireTenantPermission('specialties.manage'), c.createSpecialty);
clinicStaffRouter.patch('/specialties/:specialtyId', ...staffAuth, requireTenantPermission('specialties.manage'), c.updateSpecialty);
